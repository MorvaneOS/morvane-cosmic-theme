#!/usr/bin/env python3
"""Builds the MorvaneOS Cosmic theme and defaults.

    python tools/build.py [root]

Needs Python and Rust (cargo): the theme is computed by tools/compute-theme with
Cosmic's own theme code, from the MorvaneOS colours below. The argument is the root
to read Cosmic's own defaults from ('/' by default; its /usr/share/cosmic, from
cosmic-settings and cosmic-bg). Output goes to data/ and profile.d/; commit it, it's
what the package installs.

Cosmic looks for system defaults in each XDG data directory in turn, and takes the
first that has a setting's whole folder (cosmic/<id>/v<n>/). Cosmic's own are in
/usr/share/cosmic, owned by its packages, so the MorvaneOS ones go in
/usr/share/morvaneos/cosmic, which profile.d/ puts first in XDG_DATA_DIRS. Users'
own settings (~/.config/cosmic) still win.
"""

import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = Path(sys.argv[1]) if len(sys.argv) > 1 else Path('/')
DATA_DIR = '/usr/share/morvaneos'
WALLPAPER = '/usr/share/backgrounds/morvaneos/twilight.png'

# The colours Cosmic builds the theme from: its accent (buttons, focus, selection),
# the window background, and tints for its greys and its text
ACCENT = '#F4A6C6'  # Pastel Pink
BACKGROUND = '#1A1220'
NEUTRAL_TINT = '#B9A3E6'  # Lavender, so Cosmic's greys lean purple
TEXT_TINT = '#F5EEF3'  # Paper

BACKGROUND_ID = 'com.system76.CosmicBackground'
# Cosmic ships no system defaults for its toolkit settings, so only the icon theme is set
TOOLKIT_ID = 'com.system76.CosmicTk'
ICONS = 'candy-icons'

PROFILE = f'''\
# MorvaneOS default look for Cosmic, from morvane-cosmic-theme: Cosmic reads its
# defaults from the first XDG data directory that has them, and this one has the
# MorvaneOS theme and wallpaper. Generated by tools/build.py, edit that instead.
case ":${{XDG_DATA_DIRS}}:" in
*:{DATA_DIR}:*) ;;
*) export XDG_DATA_DIRS="{DATA_DIR}:${{XDG_DATA_DIRS:-/usr/local/share:/usr/share}}" ;;
esac
'''


def compute_theme(out: Path) -> None:
	manifest = ROOT / 'tools' / 'compute-theme' / 'Cargo.toml'
	command = ['cargo', 'run', '--quiet', '--release', '--manifest-path', str(manifest), '--', str(out)]
	subprocess.run(command + [ACCENT, BACKGROUND, NEUTRAL_TINT, TEXT_TINT], check=True)
	# Only the current version of each; Cosmic reads older ones only when that's missing
	for folder in out.glob('cosmic/*/v1'):
		if not any(folder.iterdir()):
			folder.rmdir()


def build_background(out: Path) -> None:
	"""Cosmic's wallpaper settings, with the MorvaneOS wallpaper for every output."""
	src = SRC / 'usr/share/cosmic' / BACKGROUND_ID / 'v1'
	if not (src / 'all').is_file():
		sys.exit(f"Cosmic's wallpaper settings not found: {src} (pass the root to read /usr/share/cosmic from)")
	dest = out / 'cosmic' / BACKGROUND_ID / 'v1'
	shutil.copytree(src, dest)
	all_outputs = (src / 'all').read_text()
	start = all_outputs.index('source: Path("') + len('source: Path("')
	end = all_outputs.index('")', start)
	all_outputs = all_outputs[:start] + WALLPAPER + all_outputs[end:]
	# Cosmic's own file writes booleans as #true, which cosmic-bg can't read, so it
	# silently uses its built-in wallpaper instead (the same one, so it doesn't show)
	all_outputs = all_outputs.replace('#true', 'true').replace('#false', 'false')
	(dest / 'all').write_text(all_outputs)


def build_toolkit(out: Path) -> None:
	"""Cosmic's toolkit settings: only the icon theme; the rest keep Cosmic's defaults."""
	dest = out / 'cosmic' / TOOLKIT_ID / 'v1'
	dest.mkdir(parents=True)
	(dest / 'icon_theme').write_text(f'"{ICONS}"')


def build() -> None:
	for folder in ('data', 'profile.d'):
		shutil.rmtree(ROOT / folder, ignore_errors=True)
	data = ROOT / 'data'
	compute_theme(data)
	build_background(data)
	build_toolkit(data)
	(ROOT / 'profile.d').mkdir()
	(ROOT / 'profile.d' / 'morvane-cosmic-theme.sh').write_text(PROFILE)
	for folder in sorted((data / 'cosmic').glob('*/v*')):
		print(f'{folder.relative_to(data)}: {sum(1 for _ in folder.iterdir())} settings')


if __name__ == '__main__':
	build()
